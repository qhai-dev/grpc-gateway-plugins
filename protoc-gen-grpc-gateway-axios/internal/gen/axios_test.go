// TestMultiSegmentPathIsEncodedPerSegment is the regression guard for the encoding
// rule in docs/v1.md §4.7: a value such as `shippers/123` must keep its slash, or
// the gateway, which matches that slash as a separator, will not match the route.
func TestMultiSegmentPathIsEncodedPerSegment(t *testing.T) {
	api := generate(t, "")["shipping/v1/shipping_api.ts"]

	if !strings.Contains(api, "url: `/v1/${encodePathSegments(request.name)}`,") {
		t.Error("a multi-segment variable must be encoded segment by segment")
	}
	// And it must not be encoded as a single token.
	if strings.Contains(api, "encodeURIComponent(String(request.name))") {
		t.Error("a multi-segment variable must not be encoded as one token")
	}
	// The helper has to be present in the same file, since files are self-contained.
	if !strings.Contains(api, "const encodePathSegments =") {
		t.Error("the encodePathSegments helper must be inlined in the file")
	}
}

