// TestQueryExcludesPathAndBodyFields is the most important exclusion rule: a field
// bound by the path or covered by the body must not also be sent as a query
// parameter, or the gateway sets it twice.
func TestQueryExcludesPathAndBodyFields(t *testing.T) {
	out := generate(t, "")

	// UpdateUser binds user.id in the path and sends `user` as the body, so neither
	// user nor user.id may appear in the query.
	user := out["user/v1/user_api.ts"]
	if strings.Contains(user, `query.append("user`) {
		t.Error("fields covered by the body must be excluded from the query")
	}
	if strings.Contains(user, `query.append("id"`) {
		t.Error("fields bound by the path must be excluded from the query")
	}

	// CreateUser uses body: "*", so it must have no query construction at all.
	createSection := sectionBetween(user, "async createUser(", "async updateUser(")
	if strings.Contains(createSection, "URLSearchParams") {
		t.Error("body: \"*\" must not produce any query parameters")
	}
}

