func TestConfigIsSpreadBeforeUrlAndMethod(t *testing.T) {
	api := generate(t, "")["user/v1/user_api.ts"]

	idxConfig := strings.Index(api, "...config,")
	idxURL := strings.Index(api, "url: `/v1/users/${")
	if idxConfig < 0 || idxURL < 0 {
		t.Fatal("expected a request object with config and url")
	}
	if idxConfig > idxURL {
		t.Error("...config must come before url so the URL cannot be overridden")
	}
}

