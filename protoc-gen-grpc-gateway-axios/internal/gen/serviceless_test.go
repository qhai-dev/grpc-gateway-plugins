package gen_test

import (
	"strings"
	"testing"
)

// TestServiceLessFileIsHeaderOnly is the regression guard for a real defect found
// while generating the example project: a proto with no service still produces an
// output file, and that file used to carry an unused `import type { AxiosInstance }`.
//
// The file must still exist (build systems declare outputs ahead of time), but it
// must declare nothing and import nothing, so it stays clean under noUnusedLocals.
func TestServiceLessFileIsHeaderOnly(t *testing.T) {
	api := generate(t, "")["common/v1/address_api.ts"]

	if api == "" {
		t.Fatal("a proto with no service must still produce an output file")
	}
	for _, want := range []string{
		"// Code generated by protoc-gen-grpc-gateway-axios. DO NOT EDIT.",
		"// source: common/v1/address.proto",
	} {
		if !strings.Contains(api, want) {
			t.Errorf("header is missing %q", want)
		}
	}
	if strings.Contains(api, "import") {
		t.Errorf("a file with no service must not import anything, got:\n%s", api)
	}
	if strings.Contains(api, "class ") {
		t.Errorf("a file with no service must not declare a class, got:\n%s", api)
	}
}
